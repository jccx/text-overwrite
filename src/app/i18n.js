let I18N_LANG = 'en';
/* the language in use now: 'en' or 'zh' */
function i18nLang() { return I18N_LANG; }
/* the string for key, with {var} placeholders filled in; falls back to English, then to the key itself */
function t(key, vars) {
  let s = (I18N[I18N_LANG] && I18N[I18N_LANG][key] != null) ? I18N[I18N_LANG][key] : (I18N.en[key] != null ? I18N.en[key] : key);
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
/* the name of an offline font pack (FONT_PACKS keys stay as they are; only the display name is translated) */
function packDisplayName(k) {
  const key = { latin: 'packLatin', sc: 'packSc', cjk: 'packCjk', pdf: 'packPdfName' }[k];
  return key ? t(key) : (FONT_PACKS[k] ? FONT_PACKS[k].name : k);
}
/* the reader (reader/models.js) reports progress with language-neutral markers, so that its layer
   stays free of the page's language code; the markers become words here */
function ocrProgressText(s) {
  if (typeof s !== 'string') return '';
  if (s === 'ocr-prep') return t('ocrPreparing');
  const m = /^ocr-prep-pct:(\d+)$/.exec(s);
  if (m) return t('ocrPreparingPct', { pct: m[1] });
  return s;
}
/* switch the whole page to lang ('en' or 'zh') and remember the choice */
function setLang(lang) {
  if (lang !== 'en' && lang !== 'zh') lang = 'en';
  I18N_LANG = lang;
  try { localStorage.setItem(I18N_LANG_KEY, lang); } catch (e) { /* private mode: this visit only */ }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  const mark = $('brandMark');
  if (mark) mark.innerHTML = t('brandHtml');
  const btn = $('btnLang');
  if (btn) btn.textContent = lang === 'en' ? '中文' : 'English';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll('[data-i18n-alt]')) el.alt = t(el.dataset.i18nAlt);
  /* the installable build opens PDFs too, so its open / drop-hint wording differs from the artifact's */
  if (typeof BUILD !== 'undefined' && BUILD === 'pages') {
    $('btnOpen').textContent = t('openImagePdf');
    $('dropHint').textContent = t('dropHintPdf');
  }
  /* transient text in the old language: clear it rather than translate it after the fact */
  const toastEl = $('toast');
  if (toastEl) { toastEl.hidden = true; }
  try { clearTimeout(toastTimer); } catch (e) { /* toastTimer lives in util.js */ }
  try { setStatus(''); } catch (e) { /* the panel may not exist yet */ }
  try { findRender(); } catch (e) { /* no document open yet */ }
  try { offRender(); } catch (e) { /* the offline sheet is pages-only */ }
  try { buildFamilySelect(); } catch (e) { /* the font list may not exist yet */ }
  if (S.demo) $('stageNote').textContent = S.edit ? t('demoLabel') : t('demoHint');
  if (S.edit) { try { renderCands(); } catch (e) {} refresh(); }
}
/* wire the header button; called from boot(), before makeDemo() so the demo note is in the right language */
function langInit() {
  let saved = 'en';
  try { saved = localStorage.getItem(I18N_LANG_KEY) || 'en'; } catch (e) { saved = 'en'; }
  const btn = $('btnLang');
  if (btn) btn.onclick = () => setLang(I18N_LANG === 'en' ? 'zh' : 'en');
  setLang(saved === 'zh' ? 'zh' : 'en');
}
