/* =====================================================================
   app/i18n.js — the interface in two languages. English is the default;
   the header button switches to Chinese with one click, and back.
   The choice is remembered on the device (localStorage, overwrite.lang),
   so a reload keeps it. navigator.language is deliberately ignored.
   Every user-facing string lives in I18N below, keyed by a stable id;
   t(key, vars) fills in {name} style placeholders. Static text in
   src/index.html carries data-i18n / data-i18n-ph / data-i18n-aria /
   data-i18n-alt attributes; setLang() applies the dictionary to them,
   then re-renders the dynamic parts of the page (find box, offline
   sheet, font list, open edit) in the new language. Toasts and the
   match status are transient, so they are cleared rather than
   translated after the fact. The save sheet is filled in by save()/pdfSave() when it
   opens, so it keeps the language it was generated in and is not part of the static pass. Font proper names, the demo poster text
   and CJK measurement strings are data, not interface, and stay as is.
   ===================================================================== */
